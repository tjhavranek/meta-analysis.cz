"""Generate site/datasets/index.html -- the human front door to the data layer.

THIS PAGE IS THE ONE EXCEPTION to the redesign pipeline. Every other page is transformed
from a pre-redesign source; this one never existed before, so there is nothing to transform.
It is authored here in its final A2 form and written straight to site/. Consequence: it is not
rebuilt by build_variants/migrate, so if the stylesheet ever needs markup changes, this file
is the one that has to be updated by hand.

NO NUMBER IS WRITTEN BY HAND. Every count comes from site/api/v1/fragments/, regenerated by
data_layer/10_fragments.py whenever the data changes. The spec I was given quoted 41
literatures / 59,098 estimates; the fragments said 39 / 54,087. Reading the fragments is the
only way this page cannot drift.

The licence wording changed on 2026-08-03 by the owner's explicit decision: EVERYTHING on the
site is CC BY 4.0, including the datasets, the format conversions and the deposited PDFs. He
stated he takes full responsibility for that grant. The page previously carried a narrowly
scoped claim covering only the compilation; the point of the change is that a bot or a
researcher should never have to wonder whether a file here is safe to use.

The counts are the corrected set: the source files hold 65,349 ROWS, the analysis samples hold
61,305 ESTIMATES, and 54,087 of those are pooled. Quoting only the first made ~4,000 estimates
look lost against the catalogue below it.
"""
import os, re, html, json, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.normpath(os.path.join(HERE, "..", "site"))
FRAG = os.path.join(SITE, "api", "v1", "fragments")
OUT = os.path.join(SITE, "datasets", "index.html")


def frag(name):
    p = os.path.join(FRAG, f"{name}.html")
    if not os.path.isfile(p):
        sys.exit(f"missing fragment {name}.html -- run data_layer/10_fragments.py")
    return open(p, encoding="utf-8").read().strip()


def build():
    # The |t| figure is generated by tools_seo/build_zstat_figure.py from the published
    # harmonised CSV; regenerate it there, never edit the fragment or the output page.
    # It lives under redesign/, not api/v1/fragments/, because that directory belongs to
    # the data layer and this figure is a page element.
    zpath = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_fragments",
                         "zstat_figure.html")
    if not os.path.isfile(zpath):
        sys.exit("missing redesign/_fragments/zstat_figure.html -- run "
                 "tools_seo/build_zstat_figure.py")
    zfig = open(zpath, encoding="utf-8").read().strip()
    counts = {n: frag(n) for n in ("count_datasets", "count_estimates", "count_analysis",
                                   "cite_as", "doi", "doi_url", "concept_doi", "concept_doi_url",
                                   "count_harmonised_estimates", "count_harmonised_literatures",
                                   "count_domain_reviewed", "count_pairing_only",
                                   "harmonised_version")}
    # There is no count_code_traced fragment yet, and 19 + 19 does not equal 39 -- the page
    # was silently omitting the one code_traced literature. Derive it and ASSERT the three
    # categories sum to the pooled total, so the sentence can never quietly under-count again.
    def as_int(x):
        return int(str(x).replace(",", "").strip())
    n_lit = as_int(counts["count_harmonised_literatures"])
    n_dr = as_int(counts["count_domain_reviewed"])
    n_ap = as_int(counts["count_pairing_only"])
    n_ct = n_lit - n_dr - n_ap
    if n_ct < 0:
        sys.exit(f"audit counts do not sum: {n_dr} + {n_ap} > {n_lit}")
    counts["count_code_traced"] = str(n_ct)
    counts["count_code_checked"] = str(n_dr + n_ct)

    table = frag("datasets_table")
    not_pooled = frag("not_pooled")
    # This sentence used to be hand-written above the list and said "five ... two ... three"
    # while the list held four. Count the list instead: the data session owns which datasets
    # sit out and why, so the prose has to follow the fragment, not a memory of it.
    reasons = re.findall(r"<dt>(.*?)</dt>\s*<dd>(.*?)</dd>", not_pooled, re.S)
    if not reasons:
        sys.exit("not_pooled.html has no <dt>/<dd> pairs -- the lede cannot be derived")
    dupes = [d for _, d in reasons if d.strip().lower().startswith("duplicate of")]
    n_all, n_dup = len(reasons), len(dupes)
    n_prec = n_all - n_dup
    word = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six"}
    num = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six"}
    parts = []
    if n_prec:
        parts.append(f"{num.get(n_prec, n_prec)} carr{'ies' if n_prec == 1 else 'y'} "
                     f"no per-estimate standard error")
    if n_dup:
        parts.append(f"{num.get(n_dup, n_dup)} duplicate{'s' if n_dup == 1 else ''} a dataset "
                     f"already included, which would otherwise be counted twice")
    not_pooled_lede = (f"{word.get(n_all, n_all)} dataset{'' if n_all == 1 else 's'} "
                       f"{'is' if n_all == 1 else 'are'} published but stay"
                       f"{'s' if n_all == 1 else ''} out of the pooled table: "
                       + ", and ".join(parts) + ".")


    # Defects known to be present in the files people can download RIGHT NOW. The data
    # session owns the text and, more importantly, the conditions: each issue is emitted
    # only while it is still true of the shipped data, and the fragment is written empty
    # once they are all fixed. So this box retires itself at the next release instead of
    # becoming a warning that outlives its defect and starts lying the other way.
    # The version DOI is per-release and only exists once that release is deposited. The
    # `doi` FRAGMENT lags: after a version bump it still holds the previous release's DOI,
    # so pairing it with harmonised_version would tell a reader to cite 0.9.0-beta's DOI for
    # 1.0.0 data. datasets.json's top-level `doi` is the authority — it is null until the
    # deposit exists. Say so rather than publishing a wrong pairing.
    ds_json = json.load(open(os.path.join(SITE, "api", "v1", "datasets.json"),
                             encoding="utf-8"))
    live_doi = ds_json.get("doi")
    if live_doi:
        version_doi_note = (
            " In a replication package, where the exact files matter, cite this release"
            f" instead: <a href=\"https://doi.org/{live_doi}\">{live_doi}</a>, version"
            f" {counts['harmonised_version']}.")
    else:
        version_doi_note = (
            f" Version {counts['harmonised_version']} has not been deposited yet, so it has"
            " no version DOI of its own. Until it does, cite the concept DOI above and state"
            f" the version you used ({counts['harmonised_version']}); the files here are that"
            " version.")

    # "it is a beta" was hard-coded prose, written when it was true. It stayed on the page
    # through the 1.0.0 release and told readers the current table was a beta while
    # datasets.json described it as 1.0.0 -- the page contradicting the data it describes,
    # which is the exact failure this generator exists to prevent. Derive it from the version
    # instead, so it cannot be true on one release and false on the next without changing.
    _ver = counts["harmonised_version"]
    _prerelease = any(t in _ver.lower() for t in ("beta", "alpha", "rc", "-pre")) \
        or _ver.startswith("0.")
    harmonised_maturity = (
        ", and it is still a beta" if _prerelease
        else f", and it is stable as of version {_ver}")

    # The sentence used to end "The remaining N rest on arithmetic matching alone and are
    # provisional" unconditionally. At 1.0.0 that N is zero, and "the remaining 0" is noise.
    provisional_note = (
        f" The remaining {counts['count_pairing_only']} rest on arithmetic"
        " effect/standard-error matching alone and are provisional." if n_ap else "")

    known_issues = frag("known_issues")
    issues_block = (f'<div class="known-issues">\n<h2>Known issues in this release</h2>\n'
                    f'{known_issues}\n</div>\n\n') if known_issues else ""

    # The fragment ships the summary line as a <caption>, which lives INSIDE the table and
    # therefore inside .table-scroll. At 390px the scroller is 358px wide against a 756px
    # table, so the caption was swept into the horizontal scroll and clipped mid-sentence
    # ("65," was the last thing visible). Lift it out and render it above the scroller,
    # where it wraps. The fragment belongs to the data session, so do this here, not there.
    table_caption = ""
    m = re.search(r"<caption>(.*?)</caption>\s*", table, re.S)
    if m:
        table_caption = f'<p class="table-note">{m.group(1).strip()}</p>\n'
        table = table[:m.start()] + table[m.end():]

    head = f"""<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0 Strict//EN" "http://www.w3.org/TR/xhtml1/DTD/xhtml1-strict.dtd">
<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="en" lang="en">
<head>
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta http-equiv="content-type" content="text/html; charset=utf-8" />
<title>Datasets</title>
<meta name="keywords" content="meta-analysis data, effect sizes, estimate-level data, publication bias, economics datasets, open data, research synthesis" />
<link href="/style.css" rel="stylesheet" type="text/css" />
<!-- seo-meta:start -->
<!-- seo-meta:end -->
</head>
<body>
<div id="wrapper">
<div id="logo">
\t<a class="masthead-home" href="/">meta-analysis.cz</a>
\t<p class="site-name"><a href="/datasets/">Datasets</a></p>
\t<h2> <span class="mk">&raquo;</span>&nbsp;&nbsp;&nbsp; the estimates behind the papers</h2>
</div>
<div id="header">
\t<div id="menu">
\t\t<ul>
\t\t\t<li class="current_page_item"><a href="/datasets/">Datasets</a></li>
\t\t\t<li><a href="/">Data &amp; code</a></li>
\t\t\t<li><a href="/results/">Headline results</a></li>
\t\t\t<li><a href="/api/v1/README.md">API</a></li>
\t\t\t<li><a href="/LICENSE">Licence</a></li>
\t\t</ul>
\t</div>
</div>
</div>
"""

    # The site footer carries both authors' ORCID, Scholar, RePEc, Scopus, CEPR and
    # METRICS links, the collection's Zenodo citation and the licence. This page dropped
    # it the moment it started being generated instead of hand-edited, and nobody noticed
    # for a commit. Take it verbatim from the homepage rather than keeping a second copy:
    # 87 other pages carry the same block, and a copy here would drift from all of them.
    home = open(os.path.join(SITE, "index.html"), encoding="utf-8").read()
    fi = home.find('<footer class="site-foot">')
    fj = home.find("</footer>", fi)
    if fi < 0 or fj < 0:
        sys.exit("the homepage has no <footer class=\"site-foot\">; /datasets/ takes its "
                 "footer from there, so fix the homepage first")
    FOOTER = home[fi:fj + len("</footer>")]

    body = f"""<div id="page">
\t<div id="content">
\t\t<div class="post">
\t\t\t<h1 class="title">Datasets</h1>
\t\t\t<div class="entry datasets">

<p>This catalogue collects {counts['count_datasets']} estimate-level datasets from the
empirical meta-analyses on this site, each in a standard format.</p>

<p><b>There are two products here.</b> The <i>archive</i> publishes each paper's original
file with automatic CSV and Parquet conversions, a codebook and a DOI. The <i>harmonised
table</i> pools those datasets into one file with a common set of columns, so they can be
compared across literatures{harmonised_maturity}. For one paper's data use the archive; to
work across literatures use the harmonised table, and read its caveats below.</p>

<h2>One file, every literature</h2>

<p>{counts['count_harmonised_estimates']} estimate-level rows from
{counts['count_harmonised_literatures']} literatures in a single table, with the effect, its
standard error, the sample size, and the characteristics that recur across literatures.</p>

{zfig}

<b class="tool-link"><a href="/data/v1/estimates_harmonised.csv">estimates_harmonised.csv</a></b>

<p class="alt-format">Also as <a href="/data/v1/estimates_harmonised.parquet">Parquet</a>,
which is smaller and keeps column types.</p>

<pre class="usage"><code>df &lt;- read.csv("https://meta-analysis.cz/data/v1/estimates_harmonised.csv")</code></pre>

<pre class="usage"><code>import pandas as pd
df = pd.read_parquet("https://meta-analysis.cz/data/v1/estimates_harmonised.parquet")</code></pre>

<p class="caveat">Raw effect levels are not comparable across literatures. An elasticity, a
partial correlation and a dollar value per tonne of carbon all sit in the same column;
<code>effect_units</code> records which is which. Analyse within each literature. Comparing
across them needs an explicitly standardised measure, and relative changes are meaningful only
where the baseline is safely away from zero.</p>

<p>The harmonised table is version {counts['harmonised_version']}:
{counts['count_harmonised_estimates']} observations from {counts['count_harmonised_literatures']}
literatures. Every row records the file and the columns it came from, so any value can be
traced back to its published dataset.</p>

<details class="release-note"><summary>Smaller than the 0.9.0-beta table, and covering
more</summary>
<p>The beta reported 54,076 observations from 39 literatures; this one reports
{counts['count_harmonised_estimates']} from {counts['count_harmonised_literatures']}. The
count fell because the beta was wrong: the price-puzzle literature had been reshaped in a way
that repeated every estimate seven times, so roughly one row in eight of that table was a
duplicate. Those duplicates are gone, that literature now carries every impulse-response
horizon including the trough and the peak the beta discarded, and a further literature has
been added. Fewer rows, more evidence.</p>
</details>

{issues_block}

<p class="caveat">{counts['count_code_checked']} of the
{counts['count_harmonised_literatures']} pooled literatures are verified:
{counts['count_domain_reviewed']} domain-reviewed against the paper's own replication code or,
where a paper ships none, against its published results, and {counts['count_code_traced']}
code-traced.{provisional_note} Every dataset publishes an <code>audit_status</code> saying
which it is.</p>

<h2>One literature at a time</h2>

<p>The converted source files hold {counts['count_estimates']} rows, every one keeping the
variables coded for its original paper. After applying each paper's analysis selection and,
where necessary, reshaping the source data into estimate-level observations, the catalogue
below represents {counts['count_analysis']} estimates. The CSV and Parquet are automatic
conversions carrying one data sheet per source workbook, the one named in
<code>datasets.json</code>; any other sheet is absent, and no column is independently
re-checked. For anything load-bearing, work from the original file.</p>

<p>Each dataset is also published on its own, with all of the variables coded for its paper
rather than the shared subset, and a codebook describing every column.</p>

<p class="caveat">The Estimates column counts the rows in each published file after that
paper's own analysis filters, which is not always the number in the paper's abstract. Usually
the file is the analysis subset rather than the full collection; for a few literatures the
published file is genuinely narrower than the sample behind the paper, and two contribute a
row per impulse-response horizon. <a href="/api/v1/datasets.json">datasets.json</a> carries a
reconciliation for every dataset where the two counts differ, including the cases that remain
unexplained.</p>

{table_caption}<div class="table-scroll">
{table}
</div>

<h2>Published but not pooled</h2>

<p>{not_pooled_lede}</p>

{not_pooled}

<h2>Machine-readable</h2>

<p>The whole collection is available as JSON: an
<a href="/api/v1/datasets.json">index of every dataset</a> with paper, DOI, file URLs and
column roles, a <a href="/api/v1/datapackage.json">Frictionless data package</a>, and a
<a href="/api/v1/croissant.json">Croissant record</a>. Full documentation is in the
<a href="/api/v1/README.md">API README</a>.</p>

<h2>Licence and citation</h2>

<p><strong>Everything here is <a href="https://creativecommons.org/licenses/by/4.0/">CC
BY 4.0</a></strong>, including for training, provided you give credit.
<a href="/LICENSE">The licence file</a> states the terms, and the citation for the collection
is in the footer of every page.</p>

<p><strong>Each dataset was assembled for a specific paper. When you use one, cite that
paper.</strong> The index carries every paper's title, authors and DOI. That is how attribution
under CC BY is satisfied here.</p>

<p>The Zenodo identifier in that footer is the concept DOI: it always resolves to the newest
version.{version_doi_note}</p>

<div class="funding">The papers themselves, with their abstracts, figures and replication
packages, are on the <a href="/">main catalogue</a>.</div>

\t\t\t</div>
\t\t</div>
\t</div>
\t<!-- No #sidebar on purpose. The 44-row, five-column catalogue IS this page content,
\t     and beside a 15rem rail it had 576px to work in: "codebook" broke as "codebo/ok"
\t     and rows ran to five lines. With no sidebar #page falls back to one column (the
\t     :not(:has(#sidebar)) rule) and the table gets the full sheet. Nothing is lost:
\t     every link a sidebar would carry is already in the nav or the body sections. -->
</div>
{FOOTER}
</body>
</html>
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    page = head + body
    open(OUT, "w", encoding="utf-8", newline="\n").write(page)

    # self-checks: the things that would silently break the page or the pipeline
    problems = []
    if page.count("<div") != page.count("</div>"):
        problems.append(f"div imbalance: {page.count('<div')} open, {page.count('</div>')} close")
    if page.count("<h1") != 1:
        problems.append(f"{page.count('<h1')} h1 tags, expected exactly 1")
    if "{{" in page or "}}" in page:
        problems.append("an unsubstituted {{fragment}} placeholder survived")
    body_only = page[page.find('<h1 class="title">'):]
    if "—" in body_only:
        problems.append(f"{body_only.count(chr(8212))} em-dash(es) in the page body -- "
                        f"the owner reads heavy em-dash use as an AI tell; use a full stop, "
                        f"colon or comma where one will do")
    # any "beta" on the page must be about the SUPERSEDED release, never the current one
    body_txt = re.sub(r"<[^>]+>", " ", page[page.find('<h1 class="title">'):])
    for m in re.finditer(r"[^.]*beta[^.]*\.", body_txt):
        claim = re.sub(r"\s+", " ", m.group(0)).strip()
        if not _prerelease and "0.9.0-beta" not in claim:
            problems.append(f"page calls the current release a beta: {claim[:90]!r}")

    if counts["concept_doi"] not in page:
        problems.append("the page does not carry the concept DOI")
    # Never publish a version DOI the data layer does not vouch for, and never pair a DOI
    # with a version string unless datasets.json says that DOI IS this version.
    # counts["doi"] is now empty when no version DOI is minted (the data session made the
    # fragment always-written rather than conditionally-written, so a stale value cannot
    # survive). An empty string is "in" every page, so guard on it being non-empty.
    if not live_doi and counts["doi"] and counts["doi"] in page:
        problems.append(f"page carries version DOI {counts['doi']} but datasets.json has "
                        f"none for {counts['harmonised_version']} -- the doi fragment is "
                        f"stale from the previous release")
    if live_doi and live_doi not in page:
        problems.append("datasets.json has a version DOI the page does not carry")
    for must in ("/data/v1/estimates_harmonised.csv", "/api/v1/datasets.json",
                 "/api/v1/README.md", "/LICENSE"):
        if f'href="{must}"' not in page:
            problems.append(f"required link missing: {must}")
    if os.path.exists(os.path.join(SITE, "api", "index.html")) or \
       os.path.exists(os.path.join(SITE, "data", "index.html")):
        problems.append("an index.html appeared under /api/ or /data/ -- the build gate fails on this")
    for tag in ("table", "ul", "ol", "dl"):
        if len(re.findall(rf"<{tag}\b", page)) != len(re.findall(rf"</{tag}>", page)):
            problems.append(f"<{tag}> unbalanced")

    print(f"  wrote {os.path.relpath(OUT, os.path.dirname(SITE))}  ({len(page):,} bytes)")
    print(f"  counts from fragments: {counts['count_datasets']} datasets, "
          f"{counts['count_estimates']} estimates, {counts['count_harmonised_estimates']} pooled "
          f"across {counts['count_harmonised_literatures']} literatures, v{counts['harmonised_version']}")
    print(f"  catalogue rows inlined: {len(re.findall(r'<tr', table))}")
    if problems:
        print("\n  !! PROBLEMS:")
        for p in problems:
            print(f"     {p}")
        sys.exit(1)
    print("  self-checks clean")


if __name__ == "__main__":
    build()
